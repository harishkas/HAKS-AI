"""Domain models and data transfer objects for HAKS Memory Architecture."""

from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field


class MemoryDomain(str, Enum):
    """Memory domain classification."""
    PERSONAL = "personal"
    WORK = "work"


class MemoryProposalStatus(str, Enum):
    """Lifecycle status of a memory proposal."""
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class MemoryItem(BaseModel):
    """Representation of an approved persistent memory record."""
    id: str
    domain: MemoryDomain
    title: str
    content: str
    category: str = "general"
    tags: list[str] = Field(default_factory=list)
    importance: int = Field(default=1, ge=1, le=5)
    project_name: Optional[str] = None
    created_at: str
    updated_at: str
    source_conversation_id: Optional[str] = None
    is_archived: bool = False


class MemoryProposal(BaseModel):
    """A memory proposal generated by AI detection awaiting explicit user review."""
    id: str
    domain: MemoryDomain
    source_conversation_id: Optional[str] = None
    proposal_text: str
    suggested_title: str
    suggested_category: str = "general"
    suggested_tags: list[str] = Field(default_factory=list)
    suggested_importance: int = Field(default=2, ge=1, le=5)
    suggested_project: Optional[str] = None
    confidence: float = Field(default=0.75, ge=0.0, le=1.0)
    status: MemoryProposalStatus = MemoryProposalStatus.PENDING
    created_at: str
    reviewed_at: Optional[str] = None


class MemorySearchResult(BaseModel):
    """Result from a semantic or keyword memory retrieval."""
    item: MemoryItem
    score: float = Field(ge=0.0, le=1.0)
    match_type: str = "semantic"  # "exact", "keyword", "semantic"


class MemoryBackupBundle(BaseModel):
    """Portable backup bundle for a memory domain."""
    domain: MemoryDomain
    version: str = "1.0"
    exported_at: str
    item_count: int
    items: list[dict]
    is_encrypted: bool = False
